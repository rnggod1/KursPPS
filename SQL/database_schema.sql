-- Удаление таблиц
DROP TABLE IF EXISTS Детали_Закупки CASCADE;
DROP TABLE IF EXISTS Закупка CASCADE;
DROP TABLE IF EXISTS План_Закупки CASCADE;
DROP TABLE IF EXISTS Склад CASCADE;
DROP TABLE IF EXISTS Сектор_Склада CASCADE;
DROP TABLE IF EXISTS Норма_Запаса CASCADE;
DROP TABLE IF EXISTS Материал CASCADE;
DROP TABLE IF EXISTS Поставщик CASCADE;

-- 1. Поставщик
CREATE TABLE Поставщик (
    ID_Поставщика SERIAL PRIMARY KEY,
    Имя VARCHAR(255) NOT NULL,
    Адрес TEXT,
    Почта VARCHAR(100),
    Контакты VARCHAR(100),
    Статус_сотрудничества VARCHAR(50) DEFAULT 'Активен',
    Банк_реквизиты TEXT
);

-- 2. Норма_Запаса
CREATE TABLE Норма_Запаса (
    ID_Нормы SERIAL PRIMARY KEY,
    Норма DECIMAL(15, 3) NOT NULL,
    Дата_установки DATE DEFAULT CURRENT_DATE
);

-- 3. Материал
CREATE TABLE Материал (
    ID_Материала SERIAL PRIMARY KEY,
    Наименование VARCHAR(255) NOT NULL,
    Единица_товара VARCHAR(20) NOT NULL,
    Срок_годности INTEGER,
    Категория VARCHAR(100),
    ID_Нормы INTEGER,
    FOREIGN KEY (ID_Нормы) REFERENCES Норма_Запаса(ID_Нормы)
);

ALTER TABLE Норма_Запаса ADD COLUMN ID_Материала INTEGER;
ALTER TABLE Норма_Запаса ADD FOREIGN KEY (ID_Материала) REFERENCES Материал(ID_Материала);
ALTER TABLE Норма_Запаса ADD UNIQUE (ID_Материала);

-- 4. Сектор_Склада
CREATE TABLE Сектор_Склада (
    ID_Сектора SERIAL PRIMARY KEY,
    Наименование VARCHAR(100) NOT NULL,
    Описание TEXT
);

-- 5. Склад
CREATE TABLE Склад (
    ID_Запись SERIAL PRIMARY KEY,
    ID_Материала INTEGER NOT NULL,
    Количество DECIMAL(15, 3) NOT NULL,
    Дата_поставки DATE DEFAULT CURRENT_DATE,
    ID_Сектора INTEGER,
    Статус_партии VARCHAR(50) DEFAULT 'Активна',
    FOREIGN KEY (ID_Материала) REFERENCES Материал(ID_Материала),
    FOREIGN KEY (ID_Сектора) REFERENCES Сектор_Склада(ID_Сектора)
);

-- 6. Закупка
CREATE TABLE Закупка (
    ID_Закупки SERIAL PRIMARY KEY,
    ID_Поставщика INTEGER NOT NULL,
    Дата_закупки DATE NOT NULL DEFAULT CURRENT_DATE,
    Статус_оплаты VARCHAR(50) DEFAULT 'Не оплачено',
    Общая_стоимость DECIMAL(15, 2) DEFAULT 0,
    Ответственный VARCHAR(100),
    FOREIGN KEY (ID_Поставщика) REFERENCES Поставщик(ID_Поставщика)
);

-- 7. Детали_Закупки
CREATE TABLE Детали_Закупки (
    ID_Детали SERIAL PRIMARY KEY,
    ID_Закупки INTEGER NOT NULL,
    ID_Материала INTEGER NOT NULL,
    Количество DECIMAL(15, 3) NOT NULL,
    Цена_за_единицу DECIMAL(15, 2) NOT NULL,
    Партия VARCHAR(50),
    Срок_годности DATE,
    Общая_стоимость DECIMAL(15, 2) GENERATED ALWAYS AS (Количество * Цена_за_единицу) STORED,
    FOREIGN KEY (ID_Закупки) REFERENCES Закупка(ID_Закупки),
    FOREIGN KEY (ID_Материала) REFERENCES Материал(ID_Материала)
);

-- 8. План_Закупки
CREATE TABLE План_Закупки (
    ID_Плана SERIAL PRIMARY KEY,
    ID_Материала INTEGER NOT NULL,
    Плановый_месяц DATE NOT NULL,
    Статус_плана VARCHAR(50) DEFAULT 'Проект',
    Дата_создания DATE DEFAULT CURRENT_DATE,
    FOREIGN KEY (ID_Материала) REFERENCES Материал(ID_Материала)
);

