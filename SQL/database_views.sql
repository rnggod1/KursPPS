-- 1. Статистика по материалам (группировка, агрегатные функции)
CREATE OR REPLACE VIEW Статистика_Материалов AS
SELECT 
    m.ID_Материала,
    m.Наименование,
    m.Единица_товара,
    COALESCE(SUM(s.Количество), 0) AS Текущий_остаток,
    n.Норма AS Норматив,
    n.Норма - COALESCE(SUM(s.Количество), 0) AS Дефицит,
    COUNT(s.ID_Запись) AS Количество_партий
FROM Материал m
LEFT JOIN Склад s ON m.ID_Материала = s.ID_Материала AND s.Статус_партии = 'Активна'
LEFT JOIN Норма_Запаса n ON m.ID_Материала = n.ID_Материала
GROUP BY m.ID_Материала, m.Наименование, m.Единица_товара, n.Норма
ORDER BY Дефицит DESC;

-- 2. Материалы ниже нормы (вложенный запрос)
CREATE OR REPLACE VIEW Материалы_Ниже_Нормы AS
SELECT 
    ID_Материала,
    Наименование,
    Текущий_остаток,
    Норматив,
    Дефицит
FROM Статистика_Материалов
WHERE Текущий_остаток < Норматив
ORDER BY Дефицит DESC;

-- 3. Сетка планирования (декартово произведение)
CREATE OR REPLACE VIEW Сетка_Планирования AS
SELECT 
    m.ID_Материала,
    m.Наименование,
    months.Плановый_месяц,
    COALESCE(pp.Статус_плана, 'Не запланирован') AS Статус
FROM Материал m
CROSS JOIN (
    SELECT DISTINCT Плановый_месяц FROM План_Закупки
    UNION
    SELECT '2026-06-01'::DATE
    UNION
    SELECT '2026-07-01'::DATE
) AS months
LEFT JOIN План_Закупки pp ON m.ID_Материала = pp.ID_Материала 
    AND months.Плановый_месяц = pp.Плановый_месяц
ORDER BY m.ID_Материала, months.Плановый_месяц;

-- 4. Поставщики с закупками (левое соединение)
CREATE OR REPLACE VIEW Поставщики_С_Закупками AS
SELECT 
    p.ID_Поставщика,
    p.Имя AS Поставщик,
    p.Статус_сотрудничества,
    COUNT(z.ID_Закупки) AS Количество_закупок,
    COALESCE(SUM(z.Общая_стоимость), 0) AS Общая_сумма,
    MAX(z.Дата_закупки) AS Последняя_закупка
FROM Поставщик p
LEFT JOIN Закупка z ON p.ID_Поставщика = z.ID_Поставщика
GROUP BY p.ID_Поставщика, p.Имя, p.Статус_сотрудничества
ORDER BY Общая_сумма DESC;

-- 5. Закупки с поставщиками (правое соединение)
CREATE OR REPLACE VIEW Закупки_С_Поставщиками AS
SELECT 
    z.ID_Закупки,
    z.Дата_закупки,
    p.Имя AS Поставщик,
    z.Статус_оплаты,
    z.Общая_стоимость,
    z.Ответственный,
    COUNT(dz.ID_Детали) AS Позиций
FROM Поставщик p
RIGHT JOIN Закупка z ON p.ID_Поставщика = z.ID_Поставщика
LEFT JOIN Детали_Закупки dz ON z.ID_Закупки = dz.ID_Закупки
GROUP BY z.ID_Закупки, z.Дата_закупки, p.Имя, z.Статус_оплаты, 
         z.Общая_стоимость, z.Ответственный
ORDER BY z.Дата_закупки DESC;

-- 6. Сравнение поставщиков (объединение UNION)
CREATE OR REPLACE VIEW Сравнение_Поставщиков AS
SELECT 
    'С закупками' AS Категория,
    Поставщик,
    Количество_закупок
FROM Поставщики_С_Закупками
WHERE Количество_закупок > 0
UNION ALL
SELECT 
    'Без закупок' AS Категория,
    Поставщик,
    0 AS Количество_закупок
FROM Поставщики_С_Закупками
WHERE Количество_закупок = 0
ORDER BY Категория, Поставщик;

-- 7. Полный анализ закупок (комплексный запрос с CTE)
CREATE OR REPLACE VIEW Полный_Анализ_Закупок AS
WITH Сводка AS (
    SELECT 
        z.ID_Закупки,
        z.Дата_закупки,
        p.Имя AS Поставщик,
        m.Наименование AS Материал,
        dz.Количество,
        dz.Цена_за_единицу,
        dz.Общая_стоимость,
        EXTRACT(MONTH FROM z.Дата_закупки) AS Месяц,
        EXTRACT(YEAR FROM z.Дата_закупки) AS Год
    FROM Детали_Закупки dz
    JOIN Закупка z ON dz.ID_Закупки = z.ID_Закупки
    JOIN Поставщик p ON z.ID_Поставщика = p.ID_Поставщика
    JOIN Материал m ON dz.ID_Материала = m.ID_Материала
)
SELECT 
    ID_Закупки,
    Дата_закупки,
    Поставщик,
    Материал,
    Количество,
    Цена_за_единицу,
    Общая_стоимость,
    Месяц,
    Год,
    ROUND(AVG(Общая_стоимость) OVER (PARTITION BY Поставщик), 2) AS Средний_чек_поставщика,
    ROUND(AVG(Цена_за_единицу) OVER (PARTITION BY Материал), 2) AS Средняя_цена_материала
FROM Сводка
ORDER BY Дата_закупки DESC, Поставщик, Материал;

